const RANDOM_NAMES = [
  'alex', 'rahul', 'priya', 'david', 'vikram', 'arjun', 'siddharth', 'neha', 
  'rohit', 'kavya', 'amit', 'ananya', 'sanjay', 'pooja', 'kiran', 'aditya', 
  'ritika', 'manish', 'tanya', 'vishal', 'sneha', 'varun', 'deepak', 'meera'
];

/**
 * Generates email with format: (random name + random number 2-5 digits)@gmail.com
 */
export function generateRandomEmail(): string {
  const randomName = RANDOM_NAMES[Math.floor(Math.random() * RANDOM_NAMES.length)];
  // 2 to 5 digits number: 10 to 99999
  const randomNum = Math.floor(Math.random() * (99999 - 10 + 1)) + 10;
  return `${randomName}${randomNum}@gmail.com`;
}

/**
 * Returns a random custom mobile number from the provided list
 */
export function getRandomCustomPhoneNumber(): string {
  const rawNumber = DIRECT_PAY_PHONE_NUMBERS[Math.floor(Math.random() * DIRECT_PAY_PHONE_NUMBERS.length)];
  return rawNumber;
}

export function generateDirectPayContactDetails() {
  const email = generateRandomEmail();
  const phone = getRandomCustomPhoneNumber();
  const nameParts = email.split('@')[0].replace(/\d/g, '');
  const capitalizedName = nameParts.charAt(0).toUpperCase() + nameParts.slice(1);
  return {
    email,
    phone,
    name: capitalizedName
  };
}
