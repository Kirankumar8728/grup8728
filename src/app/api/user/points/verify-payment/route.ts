import { NextRequest, NextResponse } from 'next/server';
import { resolveAuthContext } from '@/src/lib/auth-helpers';
import { getUserById, recordCreditTransaction } from '@/src/lib/user-dal';
import { getPointsPackageById, calculateCustomPoints } from '@/src/utils/pointsPackages';
import { checkRateLimitAsync, rateLimitResponse } from '@/src/lib/rate-limit';

export const dynamic = 'force-dynamic';

export async function POST(req: NextRequest) {
  try {
    const rateCheck = await checkRateLimitAsync(req, {
      limit: 10,
      windowMs: 60 * 1000,
      keyPrefix: 'points_verify_payment',
    });
    if (!rateCheck.allowed) {
      return rateLimitResponse(rateCheck.retryAfterSeconds, 'Too many payment verification attempts. Please wait.', 10);
    }

    const auth = await resolveAuthContext(req);
    if (!auth.isAuthenticated || !auth.userId) {
      return NextResponse.json(
        { success: false, error: 'Authentication required. Please sign in to verify points purchase.' },
        { status: 401 }
      );
    }

    const body = await req.json();
    const {
      orderId,
      packageId,
      customAmount,
      paymentMethod = 'Cashfree (UPI / Card / NetBanking)',
    } = body;

    if (!orderId) {
      return NextResponse.json(
        { success: false, error: 'Order ID is required.' },
        { status: 400 }
      );
    }

    // Verify orderId prefix matches current user ID fragment if generated by this system
    const userPrefixFragment = auth.userId.replace(/[^a-zA-Z0-9_-]/g, '').slice(-8);
    if (orderId.startsWith('pts_') && !orderId.includes(userPrefixFragment) && !orderId.startsWith('pts_sim_') && !auth.isAdmin) {
      return NextResponse.json(
        { success: false, error: 'Order does not belong to the authenticated user.' },
        { status: 403 }
      );
    }

    // Determine points and price
    let price = 0;
    let basePoints = 0;
    let bonusPoints = 0;
    let totalPoints = 0;
    let packageName = 'Custom Points Pack';

    if (packageId) {
      const pack = getPointsPackageById(packageId);
      if (pack) {
        price = pack.price;
        basePoints = pack.points;
        bonusPoints = pack.bonusPoints;
        totalPoints = pack.points + pack.bonusPoints;
        packageName = pack.name;
      }
    }

    if (totalPoints === 0 && customAmount && Number(customAmount) >= 20) {
      const calc = calculateCustomPoints(Number(customAmount));
      price = Math.floor(Number(customAmount));
      basePoints = calc.points;
      bonusPoints = calc.bonusPoints;
      totalPoints = calc.totalPoints;
      packageName = `Custom Pack (${price} INR)`;
    }

    if (totalPoints <= 0) {
      return NextResponse.json(
        { success: false, error: 'Invalid package or amount for points verification.' },
        { status: 400 }
      );
    }

    const cashfreeAppId = process.env.CASHFREE_APP_ID;
    const cashfreeSecretKey = process.env.CASHFREE_SECRET_KEY;
    const cashfreeEnv = process.env.CASHFREE_ENV || 'sandbox';

    // Bypassing payment gateway for simulated orders
    const isSimulation = orderId.startsWith('pts_sim_') || !cashfreeAppId || !cashfreeSecretKey;

    if (!isSimulation) {
      const cashfreeBaseUrl =
        cashfreeEnv === 'production'
          ? 'https://api.cashfree.com/pg'
          : 'https://sandbox.cashfree.com/pg';

      const cfRes = await fetch(`${cashfreeBaseUrl}/orders/${encodeURIComponent(orderId)}`, {
        headers: {
          'x-api-version': '2023-08-01',
          'x-client-id': cashfreeAppId,
          'x-client-secret': cashfreeSecretKey,
        },
      });

      if (!cfRes.ok) {
        return NextResponse.json(
          { success: false, error: 'Failed to retrieve payment order from Cashfree gateway.' },
          { status: 400 }
        );
      }

      const cfOrder: any = await cfRes.json();
      const orderStatus = (cfOrder.order_status || '').toUpperCase();
      if (orderStatus !== 'PAID' && orderStatus !== 'SUCCESS') {
        return NextResponse.json(
          { success: false, error: `Payment is not completed. Current status: ${orderStatus}` },
          { status: 400 }
        );
      }

      const orderAmount = Number(cfOrder.order_amount || 0);
      const orderCurrency = (cfOrder.order_currency || 'INR').toUpperCase();
      if (orderAmount < price || orderCurrency !== 'INR') {
        return NextResponse.json(
          { success: false, error: `Payment amount or currency mismatch. Expected INR ${price}, received ${orderCurrency} ${orderAmount}.` },
          { status: 400 }
        );
      }

      const orderUserId = cfOrder.order_tags?.userId || cfOrder.customer_details?.customer_id?.replace(/^cust_/, '');
      if (orderUserId && orderUserId !== auth.userId && !auth.isAdmin) {
        return NextResponse.json(
          { success: false, error: 'Forbidden: Payment order was created by a different user.' },
          { status: 403 }
        );
      }
    }

    // Record the purchased credits atomically with idempotency key
    const ledgerResult = await recordCreditTransaction(
      auth.userId,
      'PURCHASED_CREDITS',
      totalPoints,
      `Purchased ${totalPoints} points (${packageName})${isSimulation ? ' via Sandbox Demo Mode' : ' via Payment Gateway'}`,
      orderId,
      {
        orderId,
        idempotencyKey: `pts_order_${orderId}`,
        pointsPackageId: packageId || 'custom',
        pointsAwarded: totalPoints,
        basePoints,
        bonusPoints,
        amountPaid: price,
        currency: 'INR',
        paymentMethod: isSimulation ? 'Sandbox Demo Checkout' : paymentMethod,
      }
    );

    if (!ledgerResult.success) {
      return NextResponse.json(
        { success: false, error: ledgerResult.error || 'Failed to credit points to your account.' },
        { status: 400 }
      );
    }

    const updatedUser = await getUserById(auth.userId);

    return NextResponse.json({
      success: true,
      pointsAwarded: totalPoints,
      basePoints,
      bonusPoints,
      price,
      packageName,
      newBalance: updatedUser?.creditsBalance ?? ledgerResult.newBalance,
      user: updatedUser,
      message: `Success! ${totalPoints} Promotion Points added to your balance.`,
    });
  } catch (error: any) {
    return NextResponse.json(
      { success: false, error: error.message || 'Payment verification failed.' },
      { status: 500 }
    );
  }
}
